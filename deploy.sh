#!/bin/bash

# Скрипт для автоматического развертывания приложения
# Автор: Ваше имя
# Дата: $(date)

echo "========================================="
echo "🚀 НАЧАЛО РАЗВЕРТЫВАНИЯ ПРИЛОЖЕНИЯ"
echo "========================================="
echo ""

# 1. Запуск тестов
echo "📋 Шаг 1: Запуск тестов..."
pytest
if [ $? -ne 0 ]; then
    echo "❌ ОШИБКА: Тесты не пройдены! Развертывание остановлено."
    exit 1
fi
echo "✅ Тесты успешно пройдены!"
echo ""

# 2. Обновление репозитория
echo "📦 Шаг 2: Обновление репозитория..."
git pull
if [ $? -ne 0 ]; then
    echo "⚠️  ПРЕДУПРЕЖДЕНИЕ: Не удалось обновить репозиторий. Продолжаем..."
fi
echo "✅ Репозиторий обновлен!"
echo ""

# 3. Установка зависимостей (опционально)
echo "📦 Шаг 3: Установка зависимостей..."
pip install -r requirements.txt
if [ $? -ne 0 ]; then
    echo "⚠️  ПРЕДУПРЕЖДЕНИЕ: Не удалось установить зависимости. Продолжаем..."
fi
echo ""

# 4. Запуск приложения
echo "🎯 Шаг 4: Запуск приложения..."
python main.py
if [ $? -ne 0 ]; then
    echo "❌ ОШИБКА: Приложение завершилось с ошибкой!"
    exit 1
fi

echo ""
echo "========================================="
echo "✅ РАЗВЕРТЫВАНИЕ УСПЕШНО ЗАВЕРШЕНО!"
echo "========================================="
